// src\hooks\useIsMobile.ts

import { useEffect, useState } from 'react';

/**
 * Хук для определения мобильного устройства по ширине окна
 *
 * Отслеживает изменение размеров окна браузера и возвращает булево значение,
 * указывающее, соответствует ли текущая ширина окна мобильному брейкпоинту.
 *
 * @customHook
 * @example
 * // Использование со стандартным брейкпоинтом (834px)
 * const isMobile = useIsMobile();
 *
 * // Использование с кастомным брейкпоинтом
 * const isTablet = useIsMobile(1024);
 *
 * // В компоненте с условным рендерингом
 * function MyComponent() {
 *   const isMobile = useIsMobile();
 *
 *   return (
 *     <div>
 *       {isMobile ? (
 *         <MobileView />
 *       ) : (
 *         <DesktopView />
 *       )}
 *     </div>
 *   );
 * }
 *
 * @param {number} [breakpoint=834] - Брейкпоинт в пикселях для определения мобильного устройства.
 *                                    По умолчанию 834px (iPad в портретной ориентации).
 * @returns {boolean} true, если ширина окна меньше указанного брейкпоинта, иначе false
 *
 * @description
 * Хук предоставляет реактивный способ определения мобильного устройства
 * на основе текущей ширины окна браузера. Значение обновляется при изменении
 * размеров окна.
 *
 * @features
 * - **Инициализация**: Определяет начальное состояние при монтировании компонента
 * - **Реактивность**: Автоматически обновляется при изменении размеров окна
 * - **Настраиваемость**: Позволяет задать кастомный брейкпоинт
 * - **Эффективность**: Использует нативное событие resize браузера
 *
 * @initialization
 * Хук инициализирует состояние, проверяя текущую ширину окна при первом рендере:
 * ```
 * useState(() => window.innerWidth < breakpoint)
 * ```
 * Это предотвращает несоответствие между серверным и клиентским рендером в SSR.
 *
 * @events
 * Подписывается на событие `resize` объекта window. При изменении размеров окна:
 * 1. Проверяется новая ширина окна
 * 2. Сравнивается с брейкпоинтом
 * 3. Обновляется состояние хука
 *
 * @cleanup
 * При размонтировании компонента хук удаляет обработчик события resize
 * для предотвращения утечек памяти.
 *
 * @performance
 * - Не использует дебаунс/троттлинг, так как событие resize уже оптимизировано браузером
 * - Обновление состояния происходит только при фактическом изменении условия
 *
 * @breakpoints
 * Рекомендуемые брейкпоинты:
 * - 834px: стандартный (iPad портрет)
 * - 768px: типичный планшетный брейкпоинт
 * - 1024px: планшетный/десктопный переход
 * - 375px: iPhone SE/мобильные устройства
 *
 * @common-usage
 * 1. Адаптивный рендеринг компонентов
 * 2. Условное применение стилей
 * 3. Переключение между мобильной и десктопной версиями
 * 4. Оптимизация загрузки компонентов для разных устройств
 *
 * @ssr-considerations
 * При использовании с серверным рендерингом:
 * - На сервере всегда возвращает значение по умолчанию (false)
 * - На клиенте синхронизируется при первом рендере
 * - Для избежания гидратационных ошибок используйте `useEffect` для действий,
 *   зависящих от состояния isMobile
 *
 * @see {@link https://developer.mozilla.org/en-US/docs/Web/API/Window/resize_event} Событие resize
 * @see {@link https://reactjs.org/docs/hooks-custom.html} Создание пользовательских хуков
 *
 * @note Значение 834px выбрано как ширина iPad в портретной ориентации
 * @note Хук работает только в браузерной среде (требует объекта window)
 * @note Для более сложных медиа-запросов рассмотрите использование `window.matchMedia`
 */

export function useIsMobile(breakpoint = 834) {
  const [isMobile, setIsMobile] = useState(
    () => window.innerWidth < breakpoint
  );

  useEffect(() => {
    const handler = () => setIsMobile(window.innerWidth < breakpoint);
    window.addEventListener('resize', handler);
    return () => window.removeEventListener('resize', handler);
  }, [breakpoint]);

  return isMobile;
}

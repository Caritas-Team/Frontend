import { type FC, type ReactNode } from 'react';
import styles from './styles.module.css';

/**
 * Тип пропсов для компонента MainWrapper
 * @typedef {Object} MainWrapperProps
 * @property {ReactNode} [children] - Дочерние элементы для обертки
 */

interface MainWrapperProps {
  children?: ReactNode;
}

/**
 * Основной контейнер-обертка для контента страницы с адаптивными отступами
 *
 * @component MainWrapper
 * @description
 * Компонент-обертка, который обеспечивает единое оформление и адаптивную верстку
 * для основного контента страницы. Устанавливает максимальную ширину, минимальную высоту
 * и адаптивные отступы для различных размеров экрана.
 *
 * **Ключевые особенности:**
 * - Ограничивает максимальную ширину контента для удобочитаемости
 * - Устанавливает минимальную высоту для предотвращения "провала" контента
 * - Предоставляет адаптивные отступы для десктопа, планшетов и мобильных устройств
 * - Создает единый визуальный стиль для всех страниц приложения
 *
 * @param {MainWrapperProps} props - Свойства компонента
 * @returns {JSX.Element} Контейнер-обертка с адаптивными стилями
 *
 * @example
 * // Базовое использование
 * const HomePage = () => {
 *   return (
 *     <MainWrapper>
 *       <Header />
 *       <main>
 *         <HeroSection />
 *         <FeaturesSection />
 *         <ContactForm />
 *       </main>
 *       <Footer />
 *     </MainWrapper>
 *   );
 * };
 *
 * @example
 * // Использование в роутере
 * const AppRoutes = () => {
 *   return (
 *     <Routes>
 *       <Route
 *         path="/"
 *         element={
 *           <MainWrapper>
 *             <HomePage />
 *           </MainWrapper>
 *         }
 *       />
 *       <Route
 *         path="/about"
 *         element={
 *           <MainWrapper>
 *             <AboutPage />
 *           </MainWrapper>
 *         }
 *       />
 *     </Routes>
 *   );
 * };
 *
 * @example
 * // С вложенными компонентами
 * const DashboardPage = () => {
 *   return (
 *     <MainWrapper>
 *       <DashboardHeader />
 *       <div className="dashboard-content">
 *         <Sidebar />
 *         <DashboardMain>
 *           <StatsWidgets />
 *           <RecentActivity />
 *           <ChartsSection />
 *         </DashboardMain>
 *       </div>
 *       <DashboardFooter />
 *     </MainWrapper>
 *   );
 * };
 *
 * @note
 * - Компонент использует CSS-модуль для стилизации (styles.module.css)
 * - Устанавливает относительное позиционирование (position: relative) для внутренних абсолютно позиционированных элементов
 * - Минимальная высота 812px соответствует высоте iPhone X/11/12 Pro
 * - Адаптивные отступы меняются при трех брейкпоинтах: 1200px, 833px
 * - Максимальная ширина 1200px соответствует стандартной ширине контента для десктопов
 *
 * @accessibility
 * - Компонент является структурным элементом и не требует специальных ARIA-атрибутов
 * - Обеспечивает достаточное пространство для контента, что улучшает читаемость
 * - Адаптивные отступы помогают избежать слишком узких полей на мобильных устройствах
 * - Отсутствие семантических тегов (article, main, section) должно компенсироваться вложенными компонентами
 *
 * @layout
 * **CSS-свойства:**
 * - max-width: 1200px - ограничение ширины на больших экранах
 * - min-height: 812px - минимальная высота контейнера
 * - margin: адаптивные отступы для различных устройств
 * - position: relative - относительное позиционирование
 *
 * **Брейкпоинты:**
 * - Десктоп (≥1200px): margin: 13px 80px 48px
 * - Планшет (834px-1199px): margin: 13px 34px 20px
 * - Мобильный (≤833px): margin: 31px 22px 21px
 *
 * @responsive_behavior
 * Адаптация происходит через CSS media queries:
 * 1. Десктоп (≥1200px): стандартные отступы
 * 2. Планшет (834px-1199px): уменьшенные боковые отступы
 * 3. Мобильный (≤833px): увеличенный верхний отступ, уменьшенные боковые и нижний
 *
 * @see styles.module.css - Стили компонента с адаптивными медиа-запросами
 *
 * @design
 * Компонент решает следующие задачи:
 * 1. Обеспечивает консистентное расположение контента на всех страницах
 * 2. Создает комфортные для чтения поля (margins) на всех устройствах
 * 3. Предотвращает растягивание контента на сверхшироких мониторах
 * 4. Гарантирует минимальную высоту для страниц с малым контентом
 * 5. Упрощает создание адаптивных интерфейсов через единые отступы
 * 6. Служит основой для построения сетки страницы
 *
 * @grid_system
 * Компонент может служить основой для сетки:
 * - Внешняя обертка: MainWrapper
 * - Внутренние колонки: использование CSS Grid или Flexbox
 * - Адаптивные отступы: обеспечиваются самим MainWrapper
 * - Максимальная ширина: ограничивает сетку на больших экранах
 *
 * @performance
 * - Использование CSS-модулей обеспечивает локальную область видимости стилей
 * - Медиа-запросы обрабатываются браузером эффективно
 * - Отсутствие сложных вычислений в JavaScript
 * - Минимальная высота помогает избежать перерасчета layout при динамическом контенте
 */

export const MainWrapper: FC<MainWrapperProps> = ({ children }) => {
  return <div className={styles.wrapper}>{children}</div>;
};

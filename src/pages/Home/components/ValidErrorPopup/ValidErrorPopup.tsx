/**
 * Попап-компонент для отображения ошибок валидации отчетов
 *
 * Модальное окно, которое показывает пользователю список ошибок валидации
 * при загрузке или обработке отчетов. Используется для информирования
 * о проблемах с данными и предоставления инструкций по исправлению.
 *
 * @component
 * @example
 * // Простое использование с одной ошибкой
 * <ValidErrorPopup
 *   isOpen={true}
 *   doClose={() => setOpen(false)}
 *   errors="Файл содержит некорректный формат даты"
 * />
 *
 * // Использование с несколькими ошибками
 * <ValidErrorPopup
 *   isOpen={isErrorOpen}
 *   doClose={handleCloseError}
 *   errors={[
 *     "Отсутствует обязательное поле 'Дата'",
 *     "Некорректный формат данных в колонке 'Имя'",
 *     "Файл превышает максимальный размер"
 *   ]}
 * />
 *
 * @typedef {Object} ValidErrorPopupProps
 * @property {boolean} isOpen - Флаг открытия/закрытия модального окна
 * @property {() => void} doClose - Callback-функция для закрытия попапа
 * @property {string | string[]} errors - Ошибка или массив ошибок для отображения
 *
 * @param {ValidErrorPopupProps} props - Пропсы компонента
 * @param {boolean} props.isOpen - Управляет видимостью модального окна
 * @param {() => void} props.doClose - Функция, вызываемая при закрытии попапа
 * @param {string | string[]} props.errors - Текст ошибки или список ошибок валидации
 *
 * @returns {JSX.Element} Возвращает модальное окно со списком ошибок
 *
 * @description
 * Компонент отображает пользовательские ошибки валидации в формате модального окна.
 * Используется для информирования о проблемах при загрузке отчетов или обработке данных.
 *
 * @structure
 * Попап содержит:
 * 1. Иконку ошибки (красный восклицательный знак)
 * 2. Заголовок "Ошибка валидации отчетов!"
 * 3. Список ошибок (если передано несколько)
 * 4. Инструкцию по исправлению
 *
 * @features
 * #### Гибкая обработка ошибок:
 * - Принимает как строку с одной ошибкой, так и массив строк
 * - Автоматически преобразует строку в массив из одного элемента
 *
 * #### Единая инструкция:
 * - Всегда показывает стандартную инструкцию:
 *   "Пожалуйста, поправьте и перезагрузите файлы"
 *
 * #### Ключевые аспекты:
 * - Каждая ошибка отображается как элемент маркированного списка
 * - Уникальные ключи для элементов списка генерируются по индексу
 * - Использует общий компонент модального окна ModalUI
 *
 * @accessibility
 * - Иконка имеет alt-текст "Иконка ошибки валидации"
 * - Заголовок четко указывает на тип ошибки
 * - Текст инструкции понятен и содержит конкретное действие
 *
 * @styling
 * Компонент использует CSS-модуль для стилизации:
 * - `.popup`: основной контейнер попапа
 * - `.popup__img`: стили для иконки ошибки
 * - `.popup__title`: стили заголовка
 * - `.popup__content`: контейнер для контента
 * - `.popup__list`: список ошибок
 * - `.popup__text`: стили текста ошибок и инструкции
 *
 * @dependencies
 * - `ModalUI`: Базовый компонент модального окна
 * - `report.svg`: Иконка ошибки (красный восклицательный знак)
 *
 * @usage-context
 * Предполагаемые сценарии использования:
 * 1. Валидация загружаемых CSV/Excel файлов
 * 2. Проверка обязательных полей формы
 * 3. Обработка ошибок API при загрузке данных
 * 4. Валидация бизнес-правил при генерации отчетов
 *
 * @best-practices
 * 1. Передавайте конкретные, понятные пользователю сообщения об ошибках
 * 2. Группируйте связанные ошибки в массив
 * 3. Используйте этот компонент для ошибок, требующих действий пользователя
 * 4. Для технических ошибок рассмотрите альтернативные способы отображения
 *
 * @limitations
 * - Не поддерживает форматированный текст в ошибках (только plain text)
 * - Нет возможности кастомизировать инструкцию
 * - Все ошибки отображаются в одном стиле без категоризации
 *
 * @note Иконка фиксирована и не может быть изменена через пропсы
 * @note Инструкция всегда одинакова и не локализуется
 * @note Компонент не предоставляет кнопок действий - только информирование
 *
 * @see ModalUI Базовый компонент модального окна
 */

import styles from './ValidErrorPopup.module.css';
import { ModalUI } from '../Modal';
import type { FC } from 'react';
import report from './icons/report.svg';

interface ValidErrorPopupProps {
  isOpen: boolean;
  doClose: () => void;
  errors: string | string[];
}

export const ValidErrorPopup: FC<ValidErrorPopupProps> = ({
  isOpen,
  doClose,
  errors,
}) => {
  const errorsArray = Array.isArray(errors) ? errors : [errors];

  return (
    <ModalUI isOpen={isOpen} doClose={doClose}>
      <div className={styles.popup}>
        <img
          className={styles.popup__img}
          src={report}
          alt="Иконка ошибки валидации"
        />
        <h2 className={styles.popup__title}>Ошибка валидации отчетов!</h2>
        <div className={styles.popup__content}>
          <ul className={styles.popup__list}>
            {errorsArray.map((error, index) => (
              <li className={styles.popup__text} key={index}>
                {error}
              </li>
            ))}
          </ul>
          <p className={styles.popup__text}>
            Пожалуйста, поправьте и перезагрузите файлы
          </p>
        </div>
      </div>
    </ModalUI>
  );
};

export default ValidErrorPopup;

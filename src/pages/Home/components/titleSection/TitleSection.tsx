import React from 'react';
import style from './TitleSection.module.css';
type TTitleSection = {
  className?: string;
};

/**
 * Компонент секции с заголовком и подзаголовком для калькулятора динамики
 *
 * Простой презентационный компонент, отображающий основной заголовок
 * и поясняющий подзаголовок для страницы или раздела калькулятора динамики.
 * Используется для введения пользователя в контекст работы с инструментом.
 *
 * @component
 * @example
 * // Базовое использование
 * <TitleSection />
 *
 * // С дополнительным классом для стилизации
 * <TitleSection className="my-custom-class" />
 *
 * // В составе страницы
 * function CalculatorPage() {
 *   return (
 *     <div>
 *       <TitleSection />
 *       <CalculatorForm />
 *       <ResultsSection />
 *     </div>
 *   );
 * }
 *
 * @typedef {Object} TTitleSection
 * @property {string} [className] - Дополнительные CSS-классы для контейнера секции
 *
 * @param {TTitleSection} props - Пропсы компонента
 * @param {string} [props.className] - Дополнительный CSS-класс для кастомизации стилей секции
 *
 * @returns {JSX.Element} Возвращает секцию с заголовком и подзаголовком
 *
 * @description
 * Компонент выполняет роль вводной секции, которая:
 * 1. Сообщает пользователю название инструмента ("Калькулятор динамики")
 * 2. Объясняет ограничения инструмента (отсутствие хранения данных)
 * 3. Устанавливает правильные ожидания от использования
 *
 * @structure
 * Секция состоит из двух текстовых элементов:
 * 1. `<h1>` с классом `style.title`: "Калькулятор динамики"
 * 2. `<p>` с классом `style.subtitle`: поясняющий текст об ограничениях
 *
 * @content
 * Фиксированный контент (не настраивается через пропсы):
 * - Заголовок: "Калькулятор динамики"
 * - Подзаголовок: "Мы не храним данные, а только предоставляем инструмент для расчёта"
 *
 * @purpose
 * Основные цели компонента:
 * 1. **Идентификация**: Четко обозначает, какой инструмент перед пользователем
 * 2. **Управление ожиданиями**: Предупреждает об отсутствии хранения данных
 * 3. **Доверие**: Прозрачно сообщает о функциональных ограничениях
 * 4. **Визуальная иерархия**: Создает точку входа для страницы калькулятора
 *
 * @styling
 * Использует CSS-модуль для изоляции стилей:
 * - `.section`: стили контейнера секции
 * - `.title`: стили основного заголовка h1
 * - `.subtitle`: стили поясняющего текста
 *
 * Переданный через пропсы `className` добавляется к основному контейнеру,
 * позволяя переопределять или дополнять базовые стили.
 *
 * @accessibility
 * - Заголовок использует семантический тег `<h1>` для правильной иерархии
 * - Подзаголовок использует `<p>` для параграфа текста
 * - Компонент не содержит интерактивных элементов, только текст
 *
 * @limitations
 * - Контент фиксирован и не локализуется
 * - Нет возможности изменить текст через пропсы
 * - Не поддерживает дополнительный контент (иконки, изображения)
 *
 * @note Текст подзаголовка важен для соблюдения политики конфиденциальности
 * @note Компонент не содержит интерактивных элементов или состояния
 * @note Идеально подходит для статических страниц и лендингов
 *
 */

export const TitleSection: React.FC<TTitleSection> = ({ className }) => {
  return (
    <section
      className={className ? `${className} ${style.section}` : style.section}
    >
      <h1 className={style.title}>Калькулятор динамики</h1>
      <p className={style.subtitle}>
        Мы не храним данные, а только предоставляем инструмент для расчёта
      </p>
    </section>
  );
};

import React from 'react';
import styles from './Delta.module.css';
import ArrowUp from '@/assets/keyboard_double_arrow_up.svg';
import ArrowDown from '@/assets/keyboard_double_arrow_down.svg';

/**
 * Тип пропсов для компонента Delta
 * @typedef {Object} DeltaProps
 * @property {string} text - Текстовая метка значения (например, "50%", "-25%", "+15")
 * @property {boolean} up - Направление изменения: true - рост/положительное, false - снижение/отрицательное
 */

type DeltaProps = {
  text: string; // Например "50%" или "-25%"
  up: boolean; // true → вверх, false → вниз
};

/**
 * Индикатор изменения значения со стрелкой направления
 *
 * @component Delta
 * @description
 * Визуальный компонент для отображения изменения величины со стрелкой,
 * указывающей направление изменения (рост или снижение). Используется
 * для представления дельты, процентного изменения, прироста или других
 * сравнительных показателей.
 *
 * **Визуальная структура:**
 * - Стрелка вверх (↑) или вниз (↓) в зависимости от параметра `up`
 * - Текстовое значение с знаком (например, "+25%", "-15", "0%")
 *
 * **Типичное использование:**
 * - Отображение изменения цен, показателей, статистики
 * - Визуализация трендов в дашбордах и отчетах
 * - Отображение процентного изменения в сравнениях
 *
 * @param {DeltaProps} props - Свойства компонента
 * @returns {JSX.Element} Индикатор изменения со стрелкой и значением
 *
 * @example
 * // Положительное изменение (рост)
 * <Delta text="+25%" up={true} />
 * // Отобразит: ↑ +25%
 *
 * @example
 * // Отрицательное изменение (снижение)
 * <Delta text="-15%" up={false} />
 * // Отобразит: ↓ -15%
 *
 * @example
 * // Нулевое изменение (обычно показывается без стрелки или со специальным значением)
 * // В текущей реализации нужно выбрать up или down
 * <Delta text="0%" up={true} />
 * // Или: <Delta text="0%" up={false} />
 *
 * @example
 * // Использование в таблице с показателями
 * const metrics = [
 *   { name: 'Конверсия', value: '15%', change: '+3%', positive: true },
 *   { name: 'Отток', value: '5%', change: '-2%', positive: false }
 * ];
 *
 * return (
 *   <table>
 *     {metrics.map(metric => (
 *       <tr key={metric.name}>
 *         <td>{metric.name}</td>
 *         <td>{metric.value}</td>
 *         <td>
 *           <Delta text={metric.change} up={metric.positive} />
 *         </td>
 *       </tr>
 *     ))}
 *   </table>
 * );
 *
 * @note
 * - Стрелки используются из SVG-ассетов: ArrowUp и ArrowDown
 * - Знак (+ или -) в тексте должен указываться вручную в параметре `text`
 * - Компонент не валидирует согласованность знака в `text` и направления `up`
 * - Стрелка является чисто декоративным элементом для визуального указания направления
 *
 * @warning
 * 1. Иконки имеют пустой alt="" - это допустимо только для декоративных элементов
 * 2. Нет обработки случая, когда изменение равно 0 (нейтральное состояние)
 * 3. Не поддерживает цветовое кодирование (зеленый для роста, красный для снижения)
 * 4. Параметр `up` может не соответствовать фактическому знаку в `text`
 * 5. Компонент не адаптивен по умолчанию
 *
 * @accessibility
 * - Иконки стрелок имеют alt="", так как они декоративные
 * - Для скринридеров можно добавить скрытый текст с описанием направления
 * - Рекомендуется использовать семантически значимые текстовые значения
 * - Рассмотреть добавление aria-label с полным описанием изменения
 *
 * @layout
 * Структура компонента:
 * ```
 * <div class="delta">
 *   <img src={up ? ArrowUp : ArrowDown} alt="" class="arrow" />
 *   <span class={text}>{text}</span>
 * </div>
 * ```
 *
 * @assets
 * - ArrowUp: '@/assets/keyboard_double_arrow_up.svg' - стрелка вверх
 * - ArrowDown: '@/assets/keyboard_double_arrow_down.svg' - стрелка вниз
 *
 * @see Delta.module.css - Стили компонента
 *
 * @todo
 * - Добавить нейтральное состояние (без стрелки или с горизонтальной стрелкой)
 * - Реализовать автоматическое определение направления по знаку в `text`
 * - Добавить цветовое кодирование (зеленый/красный) в зависимости от направления
 * - Добавить валидацию согласованности `text` и `up`
 * - Реализовать анимацию появления/изменения
 * - Добавить пропс для кастомных иконок стрелок
 * - Поддержка разных размеров (small, medium, large)
 * - Добавить tooltip с дополнительной информацией
 * - Реализовать числовое форматирование (округление, разделители тысяч)
 *
 * @design
 * Компонент решает следующие задачи:
 * 1. Быстрая визуальная идентификация направления изменения
 * 2. Согласованное отображение дельт во всем приложении
 * 3. Улучшение читаемости числовых изменений
 * 4. Создание интуитивно понятного интерфейса для сравнения значений
 * 5. Интеграция с дизайн-системой через единые иконки
 *
 * @color_semantics
 * В большинстве интерфейсов принято:
 * - Зеленый/↑: положительное изменение, рост, улучшение
 * - Красный/↓: отрицательное изменение, снижение, ухудшение
 * - Серый/→: нейтральное, без изменений
 * Текущая реализация не включает цветовое кодирование.
 */

export const Delta: React.FC<DeltaProps> = ({ text, up }) => {
  return (
    <div className={styles.delta}>
      <img src={up ? ArrowUp : ArrowDown} alt="" className={styles.arrow} />
      <span className={text}>{text}</span>
    </div>
  );
};

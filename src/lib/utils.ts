/**
 * Рассчитывает возраст человека на основе даты рождения с учетом русской грамматики
 *
 * @function calculateAge
 * @description
 * Функция вычисляет возраст в годах от переданной даты рождения до текущей даты.
 * Возвращает строку с возрастом и правильным склонением слова "год" (год/года/лет).
 *
 * Основные особенности:
 * - Проверяет валидность входной даты
 * - Обрабатывает случаи, когда дата рождения в будущем
 * - Корректно учитывает месяцы и дни для точного расчета
 * - Автоматически склоняет слово "год" в зависимости от числа
 *
 * @param {string} dateString - Дата рождения в формате строки (например: "1990-01-15")
 * @returns {string} Строка с возрастом и правильным склонением, либо:
 *                   - Пустая строка '', если дата невалидна
 *                   - Сообщение об ошибке, если дата рождения в будущем
 *
 * @throws {Error} Неявно использует функцию isValidDate, которая должна быть определена
 *
 * @example
 * // Возраст 25 лет
 * calculateAge('1998-03-20');
 * // Возвращает: "25 лет"
 *
 * @note
 * Функция предполагает наличие вспомогательной функции `isValidDate()`
 * которая проверяет валидность переданной строки с датой.
 *
 * @see isValidDate - Функция для проверки валидности даты
 */

export const calculateAge = (dateString: string) => {
  if (!isValidDate(dateString)) return '';
  const today = new Date();
  const date = new Date(dateString);
  if (today <= date) return 'дата рождения превышает текущую';
  let ageYears = today.getFullYear() - date.getFullYear();
  let ageMonths = today.getMonth() - date.getMonth();
  const ageDays = today.getDate() - date.getDate();
  if (ageDays < 0) ageMonths -= 1;
  if (ageMonths < 0) ageYears -= 1;
  let yearsText = 'лет';
  let count = ageYears % 100;
  if (count >= 5 && count <= 20) {
    yearsText = 'лет';
  } else {
    count = count % 10;
    if (count === 1) {
      yearsText = 'год';
    } else if (count >= 2 && count <= 4) {
      yearsText = 'года';
    }
  }
  const personAge: string = String(ageYears) + ' ' + yearsText;
  return personAge;
};

/**
 * Проверяет валидность строки с датой в формате YYYY-MM-DD
 *
 * @function isValidDate
 * @description
 * Функция проверяет, является ли переданная строка корректной датой
 * в формате "год-месяц-день" (YYYY-MM-DD). Выполняет три уровня проверки:
 * 1. Соответствие формату регулярному выражению
 * 2. Корректность числовых значений года, месяца и дня
 * 3. Существование даты (учитывает високосные годы, количество дней в месяцах и т.д.)
 *
 * @param {string} value - Строка для проверки. Ожидается формат "YYYY-MM-DD"
 * @returns {boolean} true, если строка является валидной датой, иначе false
 *
 * @example
 * // Корректные даты
 * isValidDate('2023-12-31'); // true
 * isValidDate('2024-02-29'); // true (високосный год)
 * isValidDate('2000-01-01'); // true
 *
 * @example
 * // Некорректные даты
 * isValidDate('2023-13-01'); // false (несуществующий месяц)
 * isValidDate('2023-02-30'); // false (в феврале нет 30 дней)
 * isValidDate('2023-04-31'); // false (в апреле 30 дней)
 * isValidDate('2023-00-15'); // false (месяц начинается с 1)
 * isValidDate('2023-12-00'); // false (день начинается с 1)
 *
 * @example
 * // Некорректный формат
 * isValidDate('31-12-2023'); // false (неправильный порядок)
 * isValidDate('2023/12/31'); // false (неправильный разделитель)
 * isValidDate('2023-12-31T10:30:00'); // false (слишком длинная строка)
 * isValidDate(''); // false
 * isValidDate('не дата'); // false
 *
 * @note
 * Функция использует конструктор Date JavaScript для валидации.
 * Важно: не проверяет, находится ли дата в разумных временных рамках
 * (например, может принять даты 0001-01-01 или 9999-12-31).
 *
 * @warning
 * Функция не принимает даты с ведущими нулями в годах (например, "0123-01-01").
 * Для проверки используется строгое регулярное выражение: /^\d{4}-\d{2}-\d{2}$/
 *
 * @see calculateAge - Пример функции, использующей эту валидацию
 */

export const formatDateShort = (dateString: string): string => {
  if (!isValidDate(dateString)) return '';
  const [year, month, day] = dateString.split('-');
  return `${day}.${month}.${year}`;
};

/**
 * Проверяет валидность строки с датой в формате YYYY-MM-DD
 *
 * @function isValidDate
 * @description
 * Функция проверяет, является ли переданная строка корректной датой
 * в формате "год-месяц-день" (YYYY-MM-DD). Выполняет три уровня проверки:
 * 1. Соответствие формату регулярному выражению
 * 2. Корректность числовых значений года, месяца и дня
 * 3. Существование даты (учитывает високосные годы, количество дней в месяцах и т.д.)
 *
 * @param {string} value - Строка для проверки. Ожидается формат "YYYY-MM-DD"
 * @returns {boolean} true, если строка является валидной датой, иначе false
 *
 * @example
 * // Корректные даты
 * isValidDate('2023-12-31'); // true
 * isValidDate('2024-02-29'); // true (високосный год)
 * isValidDate('2000-01-01'); // true
 *
 * @example
 * // Некорректные даты
 * isValidDate('2023-13-01'); // false (несуществующий месяц)
 * isValidDate('2023-02-30'); // false (в феврале нет 30 дней)
 * isValidDate('2023-04-31'); // false (в апреле 30 дней)
 * isValidDate('2023-00-15'); // false (месяц начинается с 1)
 * isValidDate('2023-12-00'); // false (день начинается с 1)
 *
 * @example
 * // Некорректный формат
 * isValidDate('31-12-2023'); // false (неправильный порядок)
 * isValidDate('2023/12/31'); // false (неправильный разделитель)
 * isValidDate('2023-12-31T10:30:00'); // false (слишком длинная строка)
 * isValidDate(''); // false
 * isValidDate('не дата'); // false
 *
 * @note
 * Функция использует конструктор Date JavaScript для валидации.
 * Важно: не проверяет, находится ли дата в разумных временных рамках
 * (например, может принять даты 0001-01-01 или 9999-12-31).
 *
 * @warning
 * Функция не принимает даты с ведущими нулями в годах (например, "0123-01-01").
 * Для проверки используется строгое регулярное выражение: /^\d{4}-\d{2}-\d{2}$/
 *
 * @see calculateAge - Пример функции, использующей эту валидацию
 */
export const isValidDate = (value: string) => {
  const dateFormat = /^(\d{4})-(\d{2})-(\d{2})$/;
  const isDateFormat: boolean = dateFormat.test(value);
  if (!isDateFormat) return false;
  const [year, month, day] = value.split('-').map(Number);
  const date = new Date(year, month - 1, day);
  return (
    date.getFullYear() === year &&
    date.getMonth() === month - 1 &&
    date.getDate() === day
  );
};

/**
 * Сокращает длинные слова в строке до заданной длины с добавлением точки
 *
 * @function makeShortName
 * @description
 * Функция принимает строку (обычно ФИО или название) и сокращает каждое слово,
 * которое превышает указанную максимальную длину. Сокращенные слова обрезаются
 * до требуемой длины с добавлением точки в конце.
 *
 * Алгоритм работы:
 * 1. Разбивает входную строку на слова по пробелам
 * 2. Для каждого слова проверяет, превышает ли оно максимальную длину
 * 3. Если превышает - обрезает до требуемой длины и добавляет точку
 * 4. Собирает обратно в строку с сохранением оригинальных пробелов
 *
 * @param {string} name - Исходная строка для обработки (например, "Иванов Иван Иванович")
 * @param {number} maxWordLength - Максимально допустимая длина слова.
 *                                 Слова длиннее этого значения будут сокращены
 * @param {number} requiredWordLength - Длина, до которой сокращаются длинные слова.
 *                                      Должна быть меньше или равна maxWordLength
 * @returns {string} Обработанная строка с сокращенными длинными словами
 *
 * @throws {TypeError} Если параметры имеют неверный тип
 * @throws {RangeError} Если requiredWordLength > maxWordLength
 *
 * @example
 * // Базовое использование
 * makeShortName('Иванов Иван Иванович', 5, 3);
 * // Возвращает: "Ива. Иван Ив."
 *
 * @example
 * // Все слова в пределах лимита
 * makeShortName('Иванов Иван', 10, 5);
 * // Возвращает: "Иванов Иван" (без изменений)
 *
 * @example
 * // Сокращение нескольких слов
 * makeShortName('Александр Сергеевич Пушкин', 7, 4);
 * // Возвращает: "Алек. Серг. Пушкин"
 *
 * @example
 * // Обработка строки с разными длинами слов
 * makeShortName('Международная организация труда', 10, 5);
 * // Возвращает: "Между. орган. труда"
 *
 * @example
 * // Пустая строка
 * makeShortName('', 5, 3); // ""
 *
 * @example
 * // Строка с лишними пробелами (сохраняются)
 * makeShortName('  Слово1   Слово2  ', 5, 3);
 * // Возвращает: "  Сло.   Сло.  "
 *
 * @note
 * Функция не изменяет регистр букв и сохраняет все пробелы между словами.
 * Если слово уже содержит точку, она будет заменена новой точкой при сокращении.
 *
 * @warning
 * Функция использует простое разбиение по пробелам и не учитывает другие
 * пробельные символы (табы, переносы строк и т.д.)
 *
 * @todo
 * - Добавить поддержку других разделителей помимо пробела
 * - Добавить опцию для сохранения существующих точек
 * - Добавить обработку дефисов в составных словах
 *
 * @see abbreviateName - Альтернативная функция для сокращения ФИО
 */

export const makeShortName = (
  name: string,
  maxWordLength: number,
  requiredWordLength: number
): string => {
  const array = name.split(' ');
  const newArray = array.map(word => {
    if (word.length > maxWordLength) {
      const shortWord = word.slice(0, requiredWordLength).concat('.');
      return shortWord;
    } else {
      return word;
    }
  });
  return newArray.join(' ');
};
